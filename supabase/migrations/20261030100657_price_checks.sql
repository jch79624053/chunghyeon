create table public.price_checks (
 id bigint generated by default as identity primary key,material_id bigint not null references public.materials(id) on delete restrict,
 source_url text not null,material_version timestamptz not null,requested_by uuid not null references auth.users(id),
 status text not null default 'pending' check(status in ('pending','candidate','manual','error')),
 price numeric(14,2) check(price>0 and price<100000000000),product_name text check(length(product_name)<=300),
 message text not null default '',checked_at timestamptz not null default clock_timestamp()
);
create index price_checks_material_time_idx on public.price_checks(material_id,checked_at desc);
create index price_checks_user_time_idx on public.price_checks(requested_by,checked_at desc);
alter table public.price_checks enable row level security;
create policy price_checks_editor_read on public.price_checks for select to authenticated using((select manager_private.is_editor()));
revoke all on public.price_checks from public,anon,authenticated;
grant select on public.price_checks to authenticated;
grant select,update on public.price_checks to service_role;
create function manager_private.request_price_check(p_material bigint) returns jsonb language plpgsql security definer set search_path='' as $$
declare m public.materials;job public.price_checks;begin
 if not manager_private.is_editor() then raise exception '관리 권한이 필요합니다.' using errcode='42501';end if;
 select * into m from public.materials where id=p_material;if not found or m.purchase_url is null then raise exception '먼저 구매 링크를 등록하세요.';end if;
 perform pg_advisory_xact_lock(p_material);
 select * into job from public.price_checks where material_id=p_material and source_url=m.purchase_url and material_version=m.updated_at and checked_at>now()-case when status in ('candidate','manual') then interval '6 hours' else interval '1 minute' end order by checked_at desc limit 1;
 if found then return to_jsonb(job)||jsonb_build_object('cached',true);end if;
 perform pg_advisory_xact_lock(hashtextextended(auth.uid()::text,1));
 if (select count(*) from public.price_checks where requested_by=auth.uid() and checked_at>now()-interval '1 minute')>=10 then raise exception '조회가 많습니다. 1분 후 다시 시도하세요.';end if;
 insert into public.price_checks(material_id,source_url,material_version,requested_by) values(m.id,m.purchase_url,m.updated_at,auth.uid()) returning * into job;
 return to_jsonb(job)||jsonb_build_object('cached',false);
end $$;
create function public.request_price_check(p_material bigint) returns jsonb language sql security invoker set search_path='' as $$select manager_private.request_price_check(p_material)$$;
revoke all on function manager_private.request_price_check(bigint) from public,anon,authenticated;
grant execute on function manager_private.request_price_check(bigint) to authenticated;
revoke all on function public.request_price_check(bigint) from public,anon;
grant execute on function public.request_price_check(bigint) to authenticated;
notify pgrst,'reload schema';
